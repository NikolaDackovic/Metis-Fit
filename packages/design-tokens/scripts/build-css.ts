/**
 * Generates dist/theme.css: CSS custom properties + a Tailwind v4 `@theme` block,
 * consumed by the admin panel and the website. Run via `pnpm --filter @grit/design-tokens build`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../src/index';

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

function flatten(obj: object, prefix: string[] = []): Array<[string, string | number]> {
  return Object.entries(obj).flatMap(([k, v]) =>
    typeof v === 'object' && v !== null
      ? flatten(v, [...prefix, kebab(k)])
      : [[[...prefix, kebab(k)].join('-'), v]],
  );
}

const colors = flatten(tokens.color);
const lines = [
  '/* Generated by @grit/design-tokens - do not edit. Source: packages/design-tokens/src/index.ts */',
  '@theme {',
  ...colors.map(([k, v]) => `  --color-${k}: ${v};`),
  ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(tokens.breakpoint).map(([k, v]) => `  --breakpoint-${k}: ${v / 16}rem;`),
  `  --font-display: '${tokens.font.display}', '${tokens.font.body}', system-ui, sans-serif;`,
  `  --font-sans: '${tokens.font.body}', '${tokens.font.arabic}', system-ui, sans-serif;`,
  ...Object.entries(tokens.motion).map(([k, v]) => `  --ease-${k}: ${v.easing};`),
  '}',
  '',
  ':root {',
  '  color-scheme: dark;',
  ...Object.entries(tokens.motion).map(([k, v]) => `  --duration-${k}: ${v.duration}ms;`),
  '}',
  '',
  "html[dir='rtl'] { --font-sans: '" + tokens.font.arabic + "', system-ui, sans-serif; }",
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root { --duration-fast: 0ms; --duration-base: 0ms; --duration-slow: 0ms; }',
  '}',
  '',
];

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../dist/theme.css');
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, lines.join('\n'));
console.warn(`wrote ${path.relative(process.cwd(), out)} (${colors.length} colors)`);
