-- GRIT DIGITAL CLUB — 014 trainer workout plans, InBody measurements, nutrition plans (AI-assisted).
-- Privacy: plans and nutrition data are the member's. A trainer writes plans only for active clients;
-- nutrition plans are visible to a trainer under the same rule as progress (relationship + consent).

-- ── InBody / extra body measurements ────────────────────────────────────────
alter table public.body_measurements
  add column height_cm numeric(5, 1) check (height_cm is null or height_cm between 100 and 250),
  add column muscle_mass_kg numeric(5, 2) check (muscle_mass_kg is null or muscle_mass_kg between 10 and 150),
  add column body_water_pct numeric(4, 1) check (body_water_pct is null or body_water_pct between 20 and 80),
  add column visceral_fat smallint check (visceral_fat is null or visceral_fat between 1 and 60),
  add column calf_cm numeric(5, 1) check (calf_cm is null or calf_cm between 15 and 80);

-- ── Workout plans assigned by a trainer ──────────────────────────────────────
create table public.workout_plans (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members (id) on delete cascade,
  trainer_id uuid references public.trainers (id) on delete set null,
  title text not null check (length(trim(title)) between 1 and 120),
  notes text check (notes is null or length(notes) <= 2000),
  is_active boolean not null default true,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger workout_plans_updated_at before update on public.workout_plans
  for each row execute function public.set_updated_at();
create index workout_plans_member_idx on public.workout_plans (member_id, is_active);

create table public.workout_plan_days (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.workout_plans (id) on delete cascade,
  position smallint not null check (position between 0 and 13),
  title text not null check (length(trim(title)) between 1 and 80), -- e.g. "Dan A — noge"
  unique (plan_id, position)
);
create table public.workout_plan_items (
  id uuid primary key default gen_random_uuid(),
  day_id uuid not null references public.workout_plan_days (id) on delete cascade,
  position smallint not null check (position between 0 and 40),
  exercise_id uuid not null references public.exercises (id) on delete restrict,
  sets smallint check (sets is null or sets between 1 and 20),
  reps text check (reps is null or length(reps) <= 20),        -- "8-10", "5", "AMRAP"
  weight_note text check (weight_note is null or length(weight_note) <= 40), -- "70% 1RM", "20 kg"
  rest_s smallint check (rest_s is null or rest_s between 0 and 900),
  note text check (note is null or length(note) <= 300),
  unique (day_id, position)
);

-- ── Nutrition plans (targets computed by the API; meals optionally generated by AI) ──
create table public.nutrition_plans (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members (id) on delete cascade,
  input jsonb not null,    -- wizard answers (goal, body data, activity, preferences)
  targets jsonb not null,  -- kcal + macros (deterministic formula, safety limits applied)
  meals jsonb,             -- AI meal plan, null when AI was unavailable
  status text not null check (status in ('ready', 'targets_only')),
  model text,
  created_at timestamptz not null default now()
);
create index nutrition_plans_member_idx on public.nutrition_plans (member_id, created_at desc);

insert into public.settings (key, value) values ('nutrition.daily_limit', '3')
on conflict (key) do nothing;

-- ── RLS ──────────────────────────────────────────────────────────────────────
alter table public.workout_plans enable row level security;
alter table public.workout_plan_days enable row level security;
alter table public.workout_plan_items enable row level security;
alter table public.nutrition_plans enable row level security;
revoke all on public.workout_plans, public.workout_plan_days, public.workout_plan_items,
  public.nutrition_plans from anon, authenticated;
grant select on public.workout_plans, public.workout_plan_days, public.workout_plan_items,
  public.nutrition_plans to authenticated;
create policy workout_plans_self on public.workout_plans for select to authenticated
  using (member_id = public.current_member_id());
create policy workout_plan_days_self on public.workout_plan_days for select to authenticated
  using (exists (select 1 from public.workout_plans p
                 where p.id = plan_id and p.member_id = public.current_member_id()));
create policy workout_plan_items_self on public.workout_plan_items for select to authenticated
  using (exists (select 1 from public.workout_plan_days d join public.workout_plans p on p.id = d.plan_id
                 where d.id = day_id and p.member_id = public.current_member_id()));
create policy nutrition_plans_self on public.nutrition_plans for select to authenticated
  using (member_id = public.current_member_id());
