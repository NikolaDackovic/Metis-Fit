-- GRIT DIGITAL CLUB - 050 F15-2: calorie counter (MyFitnessPal-style).
-- A food catalog (per 100 g, with a typical serving), searchable without diacritics. Foods come
-- from three places: the starting catalog below (average values, easy to edit), Open Food Facts
-- by barcode (cached here; only the barcode is sent), and a member's own foods (private).
-- Diary entries remember the food and the amount, so the totals stay right and re-adding is quick.

create table public.foods (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 120),
  name_en text check (name_en is null or length(name_en) <= 120),
  brand text check (brand is null or length(brand) <= 80),
  barcode text check (barcode is null or barcode ~ '^[0-9]{6,14}$'),
  serving_g numeric(6, 1) not null default 100 check (serving_g > 0 and serving_g <= 2000),
  serving_label text check (serving_label is null or length(serving_label) <= 40),
  kcal_100g numeric(6, 1) not null check (kcal_100g between 0 and 900),
  protein_100g numeric(5, 1) not null default 0 check (protein_100g between 0 and 100),
  carbs_100g numeric(5, 1) not null default 0 check (carbs_100g between 0 and 100),
  fat_100g numeric(5, 1) not null default 0 check (fat_100g between 0 and 100),
  source text not null check (source in ('catalog', 'off', 'user')),
  -- A member's own food: only they see it. Catalog and Open Food Facts rows have no owner.
  owner_id uuid references public.profiles (id) on delete cascade,
  search text generated always as (
    translate(lower(name || ' ' || coalesce(name_en, '') || ' ' || coalesce(brand, '')),
              'čćžšđ', 'cczsd')
  ) stored,
  created_at timestamptz not null default now(),
  check ((source = 'user') = (owner_id is not null))
);
create unique index foods_barcode_public_idx on public.foods (barcode) where owner_id is null and barcode is not null;
create unique index foods_barcode_owner_idx on public.foods (owner_id, barcode) where owner_id is not null and barcode is not null;
create index foods_owner_idx on public.foods (owner_id) where owner_id is not null;

alter table public.foods enable row level security;
create policy foods_api on public.foods for all to grit_api using (true) with check (true);

alter table public.food_log_entries
  add column food_id uuid references public.foods (id) on delete set null,
  add column grams numeric(6, 1) check (grams is null or (grams > 0 and grams <= 5000));

